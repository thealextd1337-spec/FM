const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
let nextId=0;
const context=vm.createContext({crypto:{randomUUID:()=>`honour-${++nextId}`}});
for(const file of ['world-catalog-v61.js','world-competition-v62.js','world-coaches-v63.js','world-match-v64.js'])vm.runInContext(fs.readFileSync(`dist/${file}`,'utf8'),context);
const foundation=fs.readFileSync('dist/world-foundation-v61.js','utf8');
vm.runInContext(foundation.slice(0,foundation.indexOf('const v61Panel=')),context);
for(const file of ['world-economy-v66.js','world-honours-v74.js'])vm.runInContext(fs.readFileSync(`dist/${file}`,'utf8'),context);
const call=(name,...args)=>vm.runInContext(name,context)(...args);
const career=call('v61CreateCareer','GER-2','honour-seed'),club=career.world.clubs.find(item=>item.id==='GER-2');
const league=career.world.competitions.find(item=>item.type==='league'&&item.country===club.countryId);
league.winnerId=club.id;
const player=club.roster.find(item=>!item.keeper),before=call('v66Salary',player);
for(let index=0;index<3;index++)player.history.push({fixtureId:`award-${index}`,season:1,clubId:club.id,competitionId:league.id,minutes:90,goals:1,assists:1,rating:8.5});
call('v74CloseSeason',career);
assert.deepEqual([...player.honours.map(item=>item.kind)].sort(),['player-of-season','title','top-scorer']);
assert(call('v66Salary',player)>before,'Auszeichnungen erhöhen künftige Gehaltsforderungen');
const firstFactor=call('v74HonourFactor',player);
call('v74CloseSeason',career);
assert.equal(player.honours.length,3,'Saisonabschluss vergibt Erfolge nur einmal');
assert.equal(call('v74HonourFactor',player),firstFactor);
for(let index=0;index<12;index++)player.honours.push({id:`extra-${index}`,kind:index%2?'title':'top-scorer'});
assert(call('v74HonourFactor',player)<=1.3,'wiederholte Erfolge bleiben gedeckelt');
assert(call('v74HonourFactor',player)-firstFactor<.14,'weitere Erfolge haben abnehmende Wirkung');
const unused=club.roster.find(item=>item!==player);
assert.equal(unused.honours.length,0,'ein Titel zählt nur nach Einsatz im Wettbewerb');
const fixture=league.fixtures.find(item=>item.homeId===club.id||item.awayId===club.id),state=call('v64MakeState',career,fixture),side=fixture.homeId===club.id?0:1,pid=side===0?state.active[0]:state.awayActive[0];
state.minute=90;state.phase='finished';state.minutes[pid]=90;state.ratings={[pid]:8.8};
const salaryBeforeMatch=call('v66Salary',career.world.clubs.find(item=>item.id===club.id).roster.find(item=>item.pid===pid));
const record=call('v64FinishFixture',career,fixture,state),winner=career.world.clubs.flatMap(item=>item.roster).find(item=>item.pid===pid);
assert.equal(record.manOfMatchPid,pid,'höchste Spielnote gewinnt Man of the Match');
assert.equal(winner.honours.filter(item=>item.kind==='man-of-the-match').length,1,'Match-Award steht im Spielerprofil');
assert.equal(call('v66Salary',winner),salaryBeforeMatch,'Match-Award beeinflusst das Gehalt nicht');
call('v64FinishFixture',career,fixture,state);
assert.equal(winner.honours.filter(item=>item.kind==='man-of-the-match').length,1,'erneutes Öffnen vergibt keinen Award');
const older=league.fixtures.find(item=>item!==fixture),oldState=call('v64MakeState',career,older);
older.matchRecord={players:[{pid,side,minutes:90,goals:1,assists:0,rating:9}],score:[1,0]};oldState.minute=90;oldState.phase='finished';
call('v64FinishFixture',career,older,oldState);
assert.equal(winner.honours.filter(item=>item.kind==='man-of-the-match').length,1,'gespeicherte Partien werden nicht nachberechnet');
console.log('PASS: persönliche Awards, Titel mit Einsatz, einmalige Vergabe und gedeckelte Gehaltswirkung');
