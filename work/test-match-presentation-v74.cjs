const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {makeContext}=require('./test-v41.cjs');
const context=makeContext();
for(const file of ['penalties-v42.js','club-identity-v44.js'])vm.runInContext(fs.readFileSync(`dist/${file}`,'utf8'),context,{filename:file});
vm.runInContext('step=function(delta){match.elapsed+=delta};draw=function(){return{player:[match.people[0].x,match.people[0].y],ball:[match.ball.x,match.ball.y],line:match.offsideVisual.lineY}}',context);
vm.runInContext(fs.readFileSync('dist/match-presentation-v74.js','utf8'),context,{filename:'match-presentation-v74.js'});
vm.runInContext("match={people:[{x:.2,y:.8}],ball:{x:.3,y:.6},offsideVisual:{x:.2,y:.4,lineY:.4},elapsed:10,halftimeBreakDone:false,halftimePause:0,goalPause:2,finished:false};for(let i=0;i<60;i++)step(.05,.05)",context);
assert.equal(vm.runInContext('match.addedMinutes[0]',context),1,'echte Unterbrechungszeit erzeugt Nachspielzeit');
assert(vm.runInContext('match.firstHalfEnd',context)>37.5);
vm.runInContext('match.elapsed=37.6',context);
assert.equal(vm.runInContext('v74ClockLabel(match)',context),'45+1′');
assert.equal(vm.runInContext('v25ClockParts().join(":")',context),'45:00:1','große Spieluhr trennt reguläre Zeit und Nachspielzeit');
vm.runInContext('match.halftimeBreakDone=true;match.elapsed=match.firstHalfEnd+10;for(let i=0;i<60;i++)step(.05,.05)',context);
assert.equal(vm.runInContext('match.addedMinutes[1]',context),1);
assert.equal(vm.runInContext('v25ClockParts()[0]',context),'60','zweite Hälfte zählt ohne die Nachspielzeit der ersten Hälfte');
vm.runInContext('match.elapsed=match.firstHalfEnd+37.6',context);
assert.equal(vm.runInContext('v74ClockLabel(match)',context),'90+1′');
assert.equal(vm.runInContext('v25ClockParts().join(":")',context),'90:00:1');
const rendered=vm.runInContext('draw()',context);
assert(Math.abs(rendered.player[0]-.8)<1e-9&&Math.abs(rendered.player[1]-.2)<1e-9);
assert(Math.abs(rendered.ball[0]-.7)<1e-9&&Math.abs(rendered.ball[1]-.4)<1e-9);
assert(Math.abs(rendered.line-.6)<1e-9);
assert.equal(vm.runInContext('match.people[0].x',context),.2,'Spielfeldberechnung behält die eigenen Koordinaten');
assert.equal(vm.runInContext('match.ball.y',context),.6);
const hit=vm.runInContext('v44VisualPositions(match.people)[0]',context);
assert.equal(hit.x,480,'Trefferfläche für Spielerinfo folgt der gedrehten Ansicht');
assert.equal(hit.y,148);
console.log('PASS: sichtbarer Seitenwechsel und begrenzte Nachspielzeit aus Unterbrechungen');
