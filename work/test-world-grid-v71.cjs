const assert=require('assert');
const fs=require('fs');
const vm=require('vm');

let nextId=0;
const context=vm.createContext({crypto:{randomUUID:()=>`grid-${++nextId}`}});
for(const file of ['world-catalog-v61.js','world-competition-v62.js','world-coaches-v63.js','world-match-v64.js'])vm.runInContext(fs.readFileSync(`dist/${file}`,'utf8'),context);
const foundation=fs.readFileSync('dist/world-foundation-v61.js','utf8');
vm.runInContext(foundation.slice(0,foundation.indexOf('const v61Panel=')),context);
const get=name=>vm.runInContext(name,context);
const career=get('v61CreateCareer')('GER-2','grid-seed');
const fixture=get('v62Fixtures')(career).find(item=>item.homeId==='GER-2'||item.awayId==='GER-2');
get('v64PrepareFixture')(career,fixture);
const state=get('v64MakeState')(career,fixture),side=fixture.homeId==='GER-2'?0:1,active=get('v64Active')(state,side),cells=get('v64EnsureCells')(state,side);
const field=active.filter(pid=>state.roles[pid]!=='gk');
assert.strictEqual(new Set(field.map(pid=>cells[pid])).size,5,'Startelf belegt fünf verschiedene Rasterfelder');
const source=field.find(pid=>state.roles[pid]==='def'),oldCell=cells[source],free=25;
assert(!field.some(pid=>cells[pid]===free));
get('v64MoveCell')(career,fixture,state,side,source,free);
assert.strictEqual(cells[source],free,'freies Feld wird gespeichert');
assert.strictEqual(state.roles[source],'def');
const other=field.find(pid=>state.roles[pid]==='mid'),otherCell=cells[other];
get('v64MoveCell')(career,fixture,state,side,source,otherCell);
assert.strictEqual(cells[source],otherCell,'besetztes Feld wird übernommen');
assert.strictEqual(cells[other],free,'anderer Spieler erhält das ursprüngliche Feld');
assert.strictEqual(state.roles[source],'mid');
assert.strictEqual(state.roles[other],'def');
assert.strictEqual(state.tactics[side].formation,fixture.plan[side===0?'home':'away'].tactics.formation);
const occupied=new Set(field.map(pid=>cells[pid]));
const attacker=field.find(pid=>state.roles[pid]==='att');
assert.throws(()=>get('v64MoveCell')(career,fixture,state,side,attacker,21),/mindestens ein Spieler/,'letzten Angreifer nicht aus der Zone ziehen');
assert.deepStrictEqual(new Set(field.map(pid=>cells[pid])),occupied,'ungültige Bewegung ändert das Raster nicht');
const midfielder=field.find(pid=>state.roles[pid]==='mid');
get('v64MoveCell')(career,fixture,state,side,midfielder,6);
assert.strictEqual(state.tactics[side].formation,'2–1–2','Zonenwechsel aktualisiert die Grundordnung');
assert.strictEqual(fixture.plan[side===0?'home':'away'].roles[midfielder],'att','Startplan übernimmt die neue Einsatzposition');
state.phase='paused';
const bench=get('v64Bench')(state,side).find(pid=>!get('v64Player')(career,fixture,side,pid).keeper);
const out=field.find(pid=>state.roles[pid]!=='gk');const inheritedCell=cells[out];
get('v64QueueSubstitution')(career,fixture,state,side,out,bench);
get('v64ExecutePending')(career,fixture,state,'Spielunterbrechung');
assert.strictEqual(cells[bench],inheritedCell,'Ersatz übernimmt das Rasterfeld');
assert.strictEqual(cells[out],undefined,'ausgewechselter Spieler bleibt nicht im Raster');
console.log('PASS: Weltkarriere nutzt eindeutige Rasterfelder, freie Ziele, Positionstausch, Zonenregeln und Feldübergabe bei Wechseln');
