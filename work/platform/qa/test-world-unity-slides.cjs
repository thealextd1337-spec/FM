'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const C=require('../../../dist/world-unity-v151.js');
const pitch=fs.readFileSync('dist/world-pitch3d-v98.js','utf8'),motion=fs.readFileSync('dist/pitch-motion-v102.js','utf8');
const ctx=vm.createContext({MATCH_SPEED:.78,v55Field:{left:.06,right:.94,top:.06,bottom:.94},Math});
vm.runInContext(pitch.slice(pitch.indexOf('function v98PitchPoint'),pitch.indexOf('function v98PitchFrame')),ctx);
vm.runInContext(motion.slice(motion.indexOf('function v102Interpolate('),motion.indexOf('// Solve against the actual model joints')),ctx);
const player={pid:'tackler',x:.5,y:.5,motionX:.01,motionY:-.01,slideActive:true};
const current={elapsed:10,slide:{tackler:player,from:{x:.5,y:.5},target:{x:.52,y:.46},progress:.4}};
const frozen=JSON.stringify(current),pose=ctx.v161UnitySlide(current,player,false);
assert.equal(pose.kind,'slide');assert.equal(pose.progress,.4);assert.equal(pose.duration,.65);
assert(pose.facing.x>0&&pose.facing.z>0);assert.equal(JSON.stringify(current),frozen);
const turned=ctx.v161UnitySlide(current,player,true);
assert(Math.abs(turned.facing.x+pose.facing.x)<1e-10&&Math.abs(turned.facing.z+pose.facing.z)<1e-10);
assert.equal(ctx.v161UnitySlide(current,{...player,slideActive:false},false),null);
assert.equal(ctx.v161UnitySlide(current,{...player,keeper:true},false),null);
const recovering={...player,recoverUntil:10.3},recovery=ctx.v161UnitySlide({elapsed:10},recovering,false);
assert.equal(recovery.kind,'slideRecovery');assert(Math.abs(recovery.progress-.5)<1e-9);
assert.equal(ctx.v161UnitySlide({elapsed:11},recovering,false).progress,1);
const camera={position:{x:0,z:35,height:20},target:{x:0,z:0},fov:42};
const frame={clock:10,elapsed:10,ball:{x:0,z:0,height:.29},players:[{id:'tackler',team:0,number:2,x:0,z:0,slideActive:true,unityAction:pose,action:{kind:'receive',progress:.2},movement:{mode:'run',facing:{x:0,z:-1}}}]};
const before=JSON.stringify(frame),pic=C.picture(frame,'s',1,camera,'paused',[0,0]);
assert.equal(pic.players[0].action,'slide');assert.equal(pic.players[0].actionId,'slide:tackler');
assert.equal(pic.players[0].progress,.4);assert.deepEqual(pic.players[0].facing,[pose.facing.x,0,pose.facing.z]);
assert.equal(JSON.stringify(frame),before);
assert.deepEqual(C.picture(frame,'s',1,camera,'paused',[0,0]),pic,'Pause has no separate pose clock');
const large=C.scaled(frame,{length:81.6,width:52.8,goalWidth:9.7});
assert(Math.abs(large.players[0].unityAction.contactWorld.x-pose.contactWorld.x*1.2)<1e-9);
assert(Math.abs(large.players[0].unityAction.facing.z-pose.facing.z*1.2)<1e-9);
assert.equal(JSON.stringify(frame),before);
const next={...frame,clock:10.1,elapsed:10.1,players:[{...frame.players[0],unityAction:{...pose,progress:.8}}]};
const buffered=ctx.v102Interpolate(frame,next,.5);
assert(Math.abs(buffered.players[0].unityAction.progress-.6)<1e-9);
assert.equal(C.picture(buffered,'s',2,camera,'live',[0,0]).players[0].action,'slide');
const transition={...next,players:[{...next.players[0],unityAction:recovery}]};
assert.equal(ctx.v102Interpolate(next,transition,.9).players[0].unityAction.kind,'slide');
assert.equal(ctx.v102Interpolate(next,transition,1).players[0].unityAction.kind,'slideRecovery');
const foul={...frame,players:[{...frame.players[0],action:{kind:'foulOffender',id:'foul:10',progress:.3}}]};
assert.equal(C.picture(foul,'s',3,camera,'replay',[0,0]).players[0].action,'foulOffender');
assert.equal(JSON.stringify(frame),before,'Projection and buffering never mutate native input');
console.log('Native slide, recovery, foul precedence, half-time heading, scaling, buffered phases and pause purity passed.');
