const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync('dist/i18n-v75.js','utf8');
const pure=source.slice(source.indexOf('const labels='),source.indexOf("let language='de'"));
const context=vm.createContext({});vm.runInContext(`${pure};globalThis.translate=translate`,context);
const translate=context.translate;
assert.equal(translate('Verhandlung öffnen'),'Open negotiation');
assert.equal(translate('Angebot senden ↗'),'Send offer ↗');
assert.equal(translate('Transfertag 1 von 5 · 11 Profis'),'Transfer day 1 of 5 · 11 professionals');
assert.equal(translate('Aktueller Verein: Irwell FC · Richtwert 1.400 Credits. Auch Spieler ohne Verkaufsliste können ein Gebot erhalten.'),'Current club: Irwell FC · Guide value 1.400 Credits. You can also bid for players who are not listed for sale.');
assert.equal(translate('Spielervertrag ausstehend · Aktuelles Gebot 840 Credits'),'Player contract pending · Current offer 840 Credits');
assert.equal(translate('Irwell FC · 1.400 Credits Ablöse · 60 Credits Gehalt · 2 Saisons'),'Irwell FC · 1.400 Credits transfer fee · 60 Credits salary · 2 seasons');
assert.equal(translate('Pressing: Ausgewogen · Passspiel: Variabel · Abwehrlinie: Neutral · Zweikämpfe: Normal'),'Pressing: Balanced · Passing: Variable · Defensive line: Neutral · Challenges: Normal');
assert.equal(translate('29. August · Frankreich · Liga 1 · Paris Central FC gegen Marseille Union'),'29 August · France · League 1 · Paris Central FC vs Marseille Union');
assert.equal(translate('1 S · 0 U · 2 N'),'1 W · 0 D · 2 L');
assert.equal(translate('Tore 3:4'),'Goals 3:4');
assert.equal(translate('Vorherige Runde'),'Previous round');
assert.equal(translate('Nachspielzeit: +5 Minuten.'),'Stoppage time: +5 minutes.');
assert.equal(translate('Eckball für Paris Central FC nach Parade von Antoine Laurent.'),'Corner for Paris Central FC after a save by Antoine Laurent.');
assert.equal(translate('Théo Laurent spielt eine Flanke auf Nathan Martin.'),'Théo Laurent sends a cross to Nathan Martin.');
assert.equal(translate('Die Flanke von Théo Laurent gerät zu weit.'),"Théo Laurent's cross goes too long.");
assert.equal(translate('Antoine Bernard foult Diego Gómez. Freistoß für Paris Valmy FC.'),'Antoine Bernard fouls Diego Gómez. Free kick for Paris Valmy FC.');
assert.equal(translate('Kurzer Abstoß: Adrien Richard auf Antoine Bernard.'),'Short goal kick: Adrien Richard to Antoine Bernard.');
assert.equal(translate('↑ Eingewechselt 76′ · 22 Min.'),'↑ Came on 76′ · 22 min');
assert.equal(translate('Wechsel: Louis Moreau geht, Mathis Petit kommt.'),'Substitution: Louis Moreau goes off, Mathis Petit comes on.');
assert.equal(translate('Halbzeitpfiff. Kurze Pause vor der zweiten Hälfte.'),'Half-time whistle. A short break before the second half.');
assert.equal(translate('Form der letzten fünf Spiele: Sieg'),'Form in the last five matches: Win');
assert.equal(translate('Sieg 3:1 gegen Milano Ferro FC'),'Win 3:1 vs Milano Ferro FC');
assert.equal(translate('Hinspiel 3 zu 1'),'First leg 3 to 1');
assert.equal(translate('↶ Rückgängig'),'↶ Undo');
assert.equal(translate('EUROPACUP · Halbfinale'),'EUROPEAN CUP · SEMI-FINAL');
assert.equal(translate('EUROPACUP · Spieltag 4'),'EUROPEAN CUP · Matchday 4');
assert.equal(translate('Ausgewechselt · 35 Min. · Note 7,2'),'Went off · 35 min · Rating 7,2');
assert.equal(translate('Ausgewechselt · 12 Min. · ohne Note'),'Went off · 12 min · Not rated');
assert.equal(translate('NÄCHSTER GEGNER · Europacup · 12. August'),'NEXT OPPONENT · European cup · 12 August');
assert.equal(translate('Zum Spielbericht'),'To match report');
assert.equal(translate('EUROPACUP · ELFMETERSCHIESSEN'),'EUROPEAN CUP · PENALTY SHOOTOUT');
assert.equal(translate('i. E. 4:3'),'penalties 4:3');
