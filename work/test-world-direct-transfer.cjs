assert(overview.includes('proof-pending')&&overview.includes('proof-rejected'),'laufende und abgelehnte Gebote bleiben gemeinsam sichtbar');
assert(overview.indexOf('Deine Angebote & Ergebnisse')<overview.indexOf('Eigene Verkaufsangebote'),'eigene Gebote stehen vor den Verkaufslisten');
assert(overview.includes('Der Spieler hat den Wechsel abgelehnt.'));
call('v72Queue',reportCareer,offers[1],'rejected',offers[1].lastChange);
const rejection=reportCareer.world.market.transferResults.at(-1);assert.strictEqual(rejection.seen,false);
context.v61CurrentCareer=reportCareer;dialog.open=false;
call('v72ShowResults');assert.strictEqual(dialog.open,false,'nicht vor dem Tageswechsel zeigen');
call('v72ReleaseResults',reportCareer);call('v72ShowResults');
assert(dialog.open&&dialog.innerHTML.includes('Transfer abgelehnt')&&dialog.innerHTML.includes('Der Spieler hat den Wechsel abgelehnt.'));
rejection.seen=true;dialog.open=false;call('v72ShowResults');assert.strictEqual(dialog.open,false,'bestätigte Absage erscheint nicht erneut');
console.log('Angebotsübersicht und bestätigungspflichtige Absagen geprüft.');
