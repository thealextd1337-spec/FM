const fs=require('fs');
const vm=require('vm');
let serial=0;
const context=vm.createContext({crypto:{randomUUID:()=>`direct-${++serial}`}});
for(const file of ['world-catalog-v61.js','world-competition-v62.js','world-coaches-v63.js','world-match-v64.js','world-nationalities-v79.js'])vm.runInContext(fs.readFileSync(`dist/${file}`,'utf8'),context);
const foundation=fs.readFileSync('dist/world-foundation-v61.js','utf8');
vm.runInContext(foundation.slice(0,foundation.indexOf('const v61Panel=')),context);
for(const file of ['world-economy-v66.js','world-transfer-list-v72.js'])vm.runInContext(fs.readFileSync(`dist/${file}`,'utf8'),context);
context.escapeHTML=value=>String(value).replace(/[&<>"']/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]));
const ui=fs.readFileSync('dist/world-market-ui-v66.js','utf8');
vm.runInContext(ui.slice(0,ui.indexOf('const v66BaseSetCareerTab=')),context);
context.v58State=()=>({});
const transferUI=fs.readFileSync('dist/world-transfer-list-ui-v72.js','utf8');
vm.runInContext(transferUI.slice(0,transferUI.indexOf("v61WorldScreen.addEventListener('change'")),context);
const dialog={open:false,innerHTML:'',showModal(){this.open=true}};
context.testDialog=dialog;
vm.runInContext('v72EnsureDialog=()=>v72Dialog=testDialog',context);
const call=(name,...args)=>vm.runInContext(name,context)(...args);
const filter=vm.runInContext('v66Filter',context);
const career=call('v61CreateCareer','GER-2','direct-transfers'),own=call('v66Club',career,'GER-2');
call('v66ChooseSponsor',career,own.id,own.sponsors[0].id);
own.balance=100000;
const market=career.world.market;
const initial=JSON.parse(JSON.stringify(career));
const seller=career.world.clubs.find(club=>club.id!==own.id&&club.roster.length===11&&club.roster.some(player=>!player.keeper&&!call('v72Listing',career,player.pid)&&call('v72Willingness',career,player.pid,own.id)!=='no'));
const player=seller.roster.find(player=>!player.keeper&&!call('v72Listing',career,player.pid)&&call('v72Willingness',career,player.pid,own.id)!=='no');
filter.selected=player.pid;
assert(!call('v66OfferHTML',career).includes('id="v66-salary"'),'keine Vertragsfelder während der Ablöseverhandlung');
assert(call('v66OfferHTML',career).includes('data-v72-open='),'direktes Angebot öffnet die zweistufige Verhandlung');
call('v72OpenListing',career,player.pid);
assert(dialog.innerHTML.includes('id="v72-fee"'));
assert(!dialog.innerHTML.includes('id="v72-salary"'));
const listingCount=market.saleListings.length,value=call('v66Value',player);
const deal=call('v72Start',career,player.pid,10);
assert.equal(deal.stage,'fee-counter');
assert.equal(deal.annual,0);
assert.equal(market.saleListings.length,listingCount,'ein Direktgebot erzeugt keine öffentliche Verkaufsliste');
assert.throws(()=>call('v72SubmitContract',career,deal.id,1000,3,5),/Vertragsangebot/);
assert.throws(()=>call('v72Start',career,player.pid,value),/bereits/);
assert(call('v66OfferHTML',career).includes(deal.lastChange));
assert(!call('v66OfferHTML',career).includes('data-v72-open='),'laufendes Gebot statt neuem Formular');
call('v72SubmitFee',career,deal.id,deal.counter);
call('v66NextMarketDay',career);
assert.equal(deal.stage,'contract');
assert(seller.roster.some(item=>item.pid===player.pid),'Ablöseeinigung allein transferiert niemanden');
assert.equal(deal.annual,0,'kein vorweggenommenes Vertragsangebot');
call('v72RenderDeal',career,deal.id);
for(const id of ['v72-salary','v72-years','v72-promise'])assert(dialog.innerHTML.includes(`id="${id}"`));
assert(!dialog.innerHTML.includes('id="v72-fee"'));
// Fortsetzen einer gespeicherten direkten Verhandlung verwendet dieselbe Ablöse.
const restored=JSON.parse(JSON.stringify(career)),restoredDeal=call('v72Negotiation',restored,deal.id);
assert.equal(restoredDeal.directAsk,value);
const salary=call('v66Consent',restored,{...restoredDeal,annual:0,years:3,promise:5}).minimum;
call('v72SubmitContract',restored,deal.id,salary,3,5);
call('v66NextMarketDay',restored);
assert.equal(restoredDeal.stage,'completed');
assert.equal(call('v66Owner',restored,player.pid).id,own.id);
assert.equal(call('v66Contract',restored,player.pid).annual,salary);
assert.equal(call('v66Contract',restored,player.pid).promise,5);
assert.equal(restored.world.transfers.filter(item=>item.pid===player.pid).length,1);
assert(call('v61ValidateCareer',restored));
// Ein am fünften Tag begonnenes Direktgebot bleibt im Transferschluss fortsetzbar.
initial.world.market.day=5;
const finalDayDeal=call('v72Start',initial,player.pid,value);
call('v66NextMarketDay',initial);
assert.equal(initial.world.market.phase,'deadline');
assert.equal(finalDayDeal.stage,'contract');
call('v72SubmitContract',initial,finalDayDeal.id,call('v66Salary',player)*3,2,3);
call('v66NextMarketDay',initial);
assert.equal(finalDayDeal.stage,'completed');
// Der letzte Torwart wird begründet abgelehnt; der Status bleibt am Angebot sichtbar.
const blocked=JSON.parse(JSON.stringify(career)),keeper=call('v66Club',blocked,seller.id).roster.find(item=>item.keeper);
filter.selected=keeper.pid;
const keeperBid=call('v66MakeBid',blocked,own.id,keeper.pid,call('v66Value',keeper),call('v66Salary',keeper)*2,2,3);
call('v66NextMarketDay',blocked);
assert.equal(keeperBid.status,'rejected');
assert(keeperBid.reason.includes('benötigt diesen Spieler'));
assert(call('v66OfferHTML',blocked).includes(keeperBid.reason),'Ablehnung bestehender Gebote bleibt sichtbar');
assert(!call('v66OfferHTML',blocked).includes('data-v72-open='));
// Auch eine neue direkte Verhandlung endet nachvollziehbar bei Kader-/Torwartschutz.
const protectedCareer=JSON.parse(JSON.stringify(career));
const protectedDeal=call('v72Start',protectedCareer,keeper.pid,call('v66Value',keeper));
call('v66NextMarketDay',protectedCareer);
assert.equal(protectedDeal.stage,'rejected');
assert(call('v66OfferHTML',protectedCareer).includes(protectedDeal.lastChange));
// Vereinslose verhandeln den Vertrag im Dialog statt im Transferformular.
const freePlayer=market.freePlayers[0];filter.selected=freePlayer.pid;
assert(!call('v66OfferHTML',career).includes('id="v66-salary"'));
call('v72OpenFreeAgent',career,freePlayer.pid);
for(const id of ['v72-salary','v72-years','v72-promise'])assert(dialog.innerHTML.includes(`id="${id}"`));
assert(dialog.innerHTML.includes('data-v72-free-offer='));
const freeBid=call('v66MakeBid',career,own.id,freePlayer.pid,0,60,2,3);
call('v72OpenFreeAgent',career,freePlayer.pid);
assert(dialog.innerHTML.includes('Spielerantwort ausstehend'));
assert(!dialog.innerHTML.includes('data-v72-free-offer='),'laufendes Angebot kann nicht doppelt gesendet werden');
call('v66NextMarketDay',career);
assert.equal(freeBid.status,'counter');
call('v72OpenFreeAgent',career,freePlayer.pid);
assert(dialog.innerHTML.includes('data-v72-free-improve='),'Gegenforderung bleibt im Dialog bearbeitbar');
console.log('Direkttransfer: getrennte Ablöse/Vertrag, Tageswechsel, Speichern/Fortsetzen, Abschluss, Torwartschutz und sichtbare Ablehnung geprüft.');

const reportCareer=JSON.parse(JSON.stringify(initial));
reportCareer.world.market.negotiations=[];reportCareer.world.market.transferResults=[];
const offers=reportCareer.world.market.negotiations;
offers.push({id:'proof-pending',pid:player.pid,buyerId:own.id,sellerId:seller.id,stage:'fee-wait',lastChange:'Antwort ausstehend'});
offers.push({id:'proof-rejected',pid:seller.roster.find(p=>p.pid!==player.pid).pid,buyerId:own.id,sellerId:seller.id,stage:'rejected',lastChange:'Der Spieler hat den Wechsel abgelehnt.'});
