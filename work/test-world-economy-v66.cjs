const assert=require('assert');
const fs=require('fs');
const vm=require('vm');
let nextId=0;
const context=vm.createContext({crypto:{randomUUID:()=>`test-${++nextId}`}});
for(const file of ['world-catalog-v61.js','world-competition-v62.js','world-coaches-v63.js','world-match-v64.js'])vm.runInContext(fs.readFileSync(`dist/${file}`,'utf8'),context);
const foundation=fs.readFileSync('dist/world-foundation-v61.js','utf8');
vm.runInContext(foundation.slice(0,foundation.indexOf('const v61Panel=')),context);
vm.runInContext(fs.readFileSync('dist/world-economy-v66.js','utf8'),context);
if(process.env.DOPPEL_SALES)vm.runInContext(fs.readFileSync('dist/world-transfer-list-v72.js','utf8'),context);
const call=(name,...args)=>vm.runInContext(name,context)(...args);
const career=call('v61CreateCareer','GER-2',process.env.DOPPEL_SEED||'economy-seed');
const own=call('v66Club',career,'GER-2');
assert.strictEqual(career.world.market.phase,'sponsor');
assert.strictEqual(career.world.contracts.length,528);
assert(career.world.clubs.every(club=>club.balance>0&&club.sponsors.length===3));
assert.strictEqual(call('v61ValidateCareer',career),true);
assert.throws(()=>call('v66MakeBid',career,'GER-2','ENG-1-player',200,200,2),/Angebot/);
const sponsor=own.sponsors[0];
call('v66ChooseSponsor',career,own.id,sponsor.id);
assert.strictEqual(career.world.market.phase,'open');
assert.throws(()=>call('v66ChooseSponsor',career,own.id,sponsor.id),/nicht mehr/);
const other=call('v66Club',career,'ENG-1'),player=other.roster[5],price=call('v66Value',player)*2,salary=call('v66Salary',player)*2;
const beforeBuyer=own.balance,beforeSeller=other.balance;
const bid=call('v66MakeBid',career,own.id,player.pid,price,salary,2,3);
call('v66NextMarketDay',career);
assert.strictEqual(bid.status,'completed',bid.reason);
assert(own.roster.some(item=>item.pid===player.pid));
assert(!other.roster.some(item=>item.pid===player.pid));
assert.strictEqual(own.balance,beforeBuyer-price);
assert.strictEqual(other.balance,beforeSeller+price);
assert.strictEqual(call('v66Contract',career,player.pid).clubId,own.id);
assert.strictEqual(call('v61ValidateCareer',career),true);
const snapshot=JSON.parse(JSON.stringify(career));
assert.strictEqual(call('v61ValidateCareer',snapshot),true,'Transferzustand ist nach Neuladen gültig');
while(career.world.market.phase==='open')call('v66NextMarketDay',career);
assert.strictEqual(career.world.market.day,5);
assert(career.world.clubs.every(club=>club.roster.length>=10&&club.roster.length<=14));
const firstFixture=call('v62AdvanceDay',career)[0];
const renewalProbe=JSON.parse(JSON.stringify(career)),renewalClub=call('v66Club',renewalProbe,'ITA-2');
const expiringContract=renewalProbe.world.contracts.find(item=>item.clubId===renewalClub.id&&item.endSeason===1),expiringPid=expiringContract.pid;
for(const contract of renewalProbe.world.contracts.filter(item=>item.clubId===renewalClub.id))contract.annual=1000;
renewalClub.balance=call('v66SalaryDue',renewalProbe,renewalClub.id)+100;
while(!renewalProbe.world.seasonFinished)call('v62AdvanceDay',renewalProbe);
assert(renewalClub.balance>=0,'KI-Verein bleibt am Saisonende zahlungsfähig');
assert(!renewalClub.roster.some(item=>item.pid===expiringPid),'KI verlängert einen für das Folgejahr unbezahlbaren Vertrag nicht');
const beforeRepeat=JSON.stringify(career.world.clubs.map(club=>club.ledger));
call('v66AfterFixture',career,firstFixture);
assert.strictEqual(JSON.stringify(career.world.clubs.map(club=>club.ledger)),beforeRepeat,'Spielbuchung ist einmalig');
const free=career.world.market.freePlayers.find(player=>!player.keeper);
const freeBid=call('v66MakeBid',career,own.id,free.pid,0,Math.round(call('v66Salary',free)*1.3/10)*10,2,2);
call('v62AdvanceDay',career);
assert.strictEqual(freeBid.status,'completed','ablösefreier Spieler entscheidet am nächsten Kalendertag');
assert(own.roster.some(item=>item.pid===free.pid));
assert.strictEqual(call('v61ValidateCareer',career),true);
let guard=0;
while(!career.world.seasonFinished&&guard++<45)call('v62AdvanceDay',career);
assert(career.world.seasonFinished);
assert(career.world.clubs.every(club=>club.id===career.manager.managedClubId||club.balance>=0));
assert.strictEqual(call('v61ValidateCareer',career),true);
const payroll=own.ledger.filter(item=>item.id.endsWith(':salary'));
assert.strictEqual(payroll.length,1);
const closed=JSON.stringify(career);
call('v66SeasonEnd',career);
assert.strictEqual(JSON.stringify(career),closed,'Saisonfinanzen werden nur einmal geschlossen');
call('v62NextSeason',career);
assert.strictEqual(career.world.market.phase,'sponsor');
assert.strictEqual(call('v61ValidateCareer',career),true);
assert(career.world.market.freePlayers.every(player=>player.history.every(item=>item.season!==1)),'auch vertragslose Spieler erhalten Saisonarchive');
const finalSeason=Number(process.env.DOPPEL_SEASONS||4);
for(let season=2;season<=finalSeason;season++){
 const managed=call('v66Club',career,career.manager.managedClubId);
 call('v66ChooseSponsor',career,managed.id,managed.sponsors[0].id);
 let marketGuard=0;
 while(career.world.market.phase==='open'&&marketGuard++<14){
  const pending=career.world.market.pendingBids.filter(item=>item.buyerId===managed.id&&item.status==='pending'),pendingIds=new Set(pending.map(item=>item.pid));
  const missing=Math.max(0,10-managed.roster.length-pending.length);
  for(let index=0;index<missing;index++){
   const needKeeper=!managed.roster.some(item=>item.keeper)&&![...pendingIds].some(pid=>call('v66Player',career,pid)?.keeper);
   const player=career.world.market.freePlayers.filter(item=>(!needKeeper||item.keeper)&&!pendingIds.has(item.pid)&&!career.world.market.decisions.some(decision=>decision.pid===item.pid&&decision.buyerId===managed.id&&['rejected','expired'].includes(decision.status))).sort((a,b)=>call('v66Salary',a)-call('v66Salary',b))[0];
   assert(player,`Saison ${season}: freier Spieler für Mindestkader`);
   call('v66MakeBid',career,managed.id,player.pid,0,Math.max(100,Math.round(call('v66Salary',player)*1.25/10)*10),2,2);pendingIds.add(player.pid);
  }
  try{call('v66NextMarketDay',career)}catch(error){if(!/mindestens zehn Profis/.test(error.message))throw error}
 }
 assert.strictEqual(career.world.market.phase,'closed',`Saison ${season}: Transferphase beendet (Kader ${managed.roster.length}, freie Spieler ${career.world.market.freePlayers.length}, Kontostand ${managed.balance}, letzte Angebote ${JSON.stringify(career.world.market.pendingBids.filter(item=>item.buyerId===managed.id).slice(-6).map(item=>[item.status,item.reason]))})`);
 while(!career.world.seasonFinished)call('v62AdvanceDay',career);
 assert(career.world.clubs.every(club=>club.id===managed.id||club.balance>=0),`Saison ${season}: KI bleibt zahlungsfähig`);
 assert.strictEqual(call('v61ValidateCareer',career),true);
 if(season<finalSeason)call('v62NextSeason',career);
}
const bytes=value=>Buffer.byteLength(JSON.stringify(value),'utf8');
assert(bytes(career)<7_000_000,`Weltspielstand bleibt unter sieben MB (${bytes(career)} Bytes, Wettbewerbe ${bytes(career.world.competitions)}, Vereine ${bytes(career.world.clubs)}, freie Spieler ${bytes(career.world.market.freePlayers)}, Gebote ${bytes(career.world.market.pendingBids)}, Entscheidungen ${bytes(career.world.market.decisions)})`);
const negotiations=call('v61CreateCareer','GER-2','negotiation-seed'),negotiatingClub=call('v66Club',negotiations,'GER-2');
call('v66ChooseSponsor',negotiations,'GER-2',negotiatingClub.sponsors[0].id);
const target=call('v66Club',negotiations,'ENG-1').roster[5];
const lowBid=call('v66MakeBid',negotiations,'GER-2',target.pid,call('v66Value',target)*2,60,2,3);
const alternateBuyer=[...negotiations.world.clubs].filter(club=>!['GER-2','ENG-1'].includes(club.id)&&!negotiations.world.market.pendingBids.some(bid=>bid.pid===target.pid&&bid.buyerId===club.id)).sort((a,b)=>b.balance-a.balance)[0];
const alternate=call('v66MakeBid',negotiations,alternateBuyer.id,target.pid,Math.round(call('v66Value',target)*1.1/10)*10,Math.round(call('v66Salary',target)*1.5/10)*10,3,4);
call('v66NextMarketDay',negotiations);
assert.strictEqual(lowBid.status,'counter','Spieler fordert bei zu geringem Gehalt einen Gegenbetrag');
assert.strictEqual(alternate.status,'pending','weiteres Gebot wartet auf das verbesserte Käuferangebot');
call('v66ImproveBid',negotiations,lowBid.id,lowBid.counter);
assert.strictEqual(lowBid.status,'completed','verbessertes Käuferangebot schließt den Wechsel ab');
assert.strictEqual(alternate.status,'rejected','andere Gebote werden erst nach dem abgeschlossenen Wechsel verworfen');
const expiring=negotiatingClub.roster[7],oldContract=call('v66Contract',negotiations,expiring.pid);
assert.strictEqual(oldContract.endSeason,1);
const refused=call('v66Renew',negotiations,expiring.pid,60,2,3);
assert.strictEqual(refused.accepted,false);
const renewed=call('v66Renew',negotiations,expiring.pid,refused.counter,2,3);
assert.strictEqual(renewed.accepted,true);
assert.strictEqual(oldContract.endSeason,2);
const sellPlayer=negotiatingClub.roster.find(player=>!player.keeper&&player.pid!==target.pid),buyer=[...negotiations.world.clubs].filter(club=>club.id!=='GER-2'&&club.roster.length<14).sort((a,b)=>b.balance-a.balance)[0];
const incoming=call('v66MakeBid',negotiations,buyer.id,sellPlayer.pid,call('v66Value',sellPlayer),Math.round(call('v66Salary',sellPlayer)*1.5/10)*10,2,3);
call('v66RespondBid',negotiations,incoming.id,true);
assert.strictEqual(incoming.status,'completed','eigener Verein entscheidet ein eingehendes Gebot');
assert.strictEqual(call('v61ValidateCareer',negotiations),true);
console.log('Weltwirtschaft: Sponsoren, Verträge, Transfers, Buchungen, Neuladen, Kadergrenzen und Saisonabschluss geprüft.');
