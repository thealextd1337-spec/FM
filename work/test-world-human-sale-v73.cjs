const assert=require('assert');
const fs=require('fs');
const vm=require('vm');
let nextId=0;
const context=vm.createContext({crypto:{randomUUID:()=>`human-sale-${++nextId}`}});
for(const file of ['world-catalog-v61.js','world-competition-v62.js','world-coaches-v63.js','world-match-v64.js'])vm.runInContext(fs.readFileSync(`dist/${file}`,'utf8'),context);
const foundation=fs.readFileSync('dist/world-foundation-v61.js','utf8');
vm.runInContext(foundation.slice(0,foundation.indexOf('const v61Panel=')),context);
for(const file of ['world-economy-v66.js','world-transfer-list-v72.js'])vm.runInContext(fs.readFileSync(`dist/${file}`,'utf8'),context);
const call=(name,...args)=>vm.runInContext(name,context)(...args);
function start(seed){const career=call('v61CreateCareer','GER-2',seed),club=call('v66Club',career,'GER-2');call('v66ChooseSponsor',career,club.id,club.sponsors[0].id);return{career,club}}
const {career,club}=start('own-sale-seed'),player=club.roster.find(item=>!item.keeper);
assert.throws(()=>call('v72ListOwn',career,club.roster.find(item=>item.keeper).pid,200),/Torwart/);
const listing=call('v72ListOwn',career,player.pid,200),market=career.world.market;
assert.strictEqual(listing.sellerId,club.id);
assert.strictEqual(listing.ask,200);
const offers=market.negotiations.filter(item=>item.pid===player.pid&&item.stage==='seller-offer');
assert(offers.length>0,'KI-Vereine geben eigenständig Kaufangebote für einen angebotenen eigenen Spieler ab');
const offer=offers[0],buyer=call('v66Club',career,offer.buyerId),balance=club.balance;
for(const other of offers.slice(1))call('v72SellerRespond',career,other.id,'reject');
call('v72SellerRespond',career,offer.id,'counter',offer.price+10);
assert.strictEqual(offer.stage,'seller-counter-wait');
assert.strictEqual(listing.ask,200,'die öffentliche Forderung bleibt trotz Gegenforderung fest');
call('v66NextMarketDay',career);
assert.strictEqual(offer.stage,'contract-wait','der Käufer entscheidet erst am nächsten Transfertag');
assert.strictEqual(offer.agreedPrice,offer.price);
assert.throws(()=>call('v72WithdrawOwn',career,player.pid),/Ablöseeinigung/);
call('v66NextMarketDay',career);
assert.strictEqual(offer.stage,'completed','nach dem Spielervertrag entscheidet der Spieler beim Tageswechsel');
assert.strictEqual(call('v66Owner',career,player.pid).id,buyer.id);
assert.strictEqual(club.balance,balance+offer.agreedPrice);
assert.strictEqual(listing.ask,200);
assert(market.transferResults.some(item=>item.negotiationId===offer.id&&item.kind==='completed'&&item.released&&!item.seen));
assert.strictEqual(call('v61ValidateCareer',JSON.parse(JSON.stringify(career))),true);
const withdrawn=start('own-withdraw-seed'),withdrawnPlayer=withdrawn.club.roster.find(item=>!item.keeper);
call('v72ListOwn',withdrawn.career,withdrawnPlayer.pid,200);
call('v72WithdrawOwn',withdrawn.career,withdrawnPlayer.pid);
assert.strictEqual(call('v72Listing',withdrawn.career,withdrawnPlayer.pid),null);
assert.throws(()=>call('v72ListOwn',withdrawn.career,withdrawnPlayer.pid,300),/bereits ein Verkaufsangebot/);
assert.strictEqual(call('v61ValidateCareer',withdrawn.career),true);
const expiring=start('own-expire-seed'),expiringPlayer=expiring.club.roster.find(item=>!item.keeper);
call('v72ListOwn',expiring.career,expiringPlayer.pid,200);
for(let day=1;day<5;day++)call('v66NextMarketDay',expiring.career);
assert(expiring.career.world.market.negotiations.some(item=>item.pid===expiringPlayer.pid&&item.stage==='seller-offer'));
call('v66NextMarketDay',expiring.career);
assert.strictEqual(expiring.career.world.market.phase,'deadline');
call('v66NextMarketDay',expiring.career);
assert.strictEqual(expiring.career.world.market.phase,'closed','unbeantwortete Kaufangebote werden zum Transferschluss abgelehnt');
assert.strictEqual(call('v66Owner',expiring.career,expiringPlayer.pid).id,expiring.club.id);
console.log('Eigene Verkaufsangebote: Profil-Einstieg, KI-Gebote, Gegenforderung, Rücknahme, Vertrag, Tageswechsel und Buchung geprüft.');
