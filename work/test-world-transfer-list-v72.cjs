const assert=require('assert');
const fs=require('fs');
const vm=require('vm');
let nextId=0;
const context=vm.createContext({crypto:{randomUUID:()=>`sale-test-${++nextId}`}});
for(const file of ['world-catalog-v61.js','world-competition-v62.js','world-coaches-v63.js','world-match-v64.js'])vm.runInContext(fs.readFileSync(`dist/${file}`,'utf8'),context);
const foundation=fs.readFileSync('dist/world-foundation-v61.js','utf8');
vm.runInContext(foundation.slice(0,foundation.indexOf('const v61Panel=')),context);
for(const file of ['world-economy-v66.js','world-transfer-list-v72.js'])vm.runInContext(fs.readFileSync(`dist/${file}`,'utf8'),context);
const call=(name,...args)=>vm.runInContext(name,context)(...args);
const career=call('v61CreateCareer','GER-2','sale-list-seed'),own=call('v66Club',career,'GER-2');
call('v66ChooseSponsor',career,own.id,own.sponsors[0].id);
const market=career.world.market,listed=market.saleListings.filter(item=>item.status==='active');
assert(listed.length>0,'KI-Vereine bieten eigenständig Spieler an');
assert(listed.every(item=>item.sellerId!==own.id&&item.ask>0&&call('v66Owner',career,item.pid)?.id===item.sellerId));
const healthy=career.world.clubs.filter(club=>club.id!==own.id&&club.roster.length===11&&!call('v72ListingPressure',career,club));
assert(healthy.length>0,'es gibt Vereine ohne Verkaufsbedarf');
assert(healthy.every(club=>!listed.some(item=>item.sellerId===club.id)),'ein normaler Kader mit gesunden Finanzen muss niemanden anbieten');
assert(listed.every(item=>call('v72ListingPressure',career,call('v66Club',career,item.sellerId))),'Startangebote brauchen einen nachvollziehbaren Finanzgrund');
const listing=listed.find(item=>call('v72Willingness',career,item.pid,own.id)!=='no'&&item.ask<own.balance&&!market.negotiations.some(entry=>entry.pid===item.pid));
assert(listing,'ein für den eigenen Verein erreichbares Angebot existiert');
const publicAsk=listing.ask,playerId=listing.pid,seller=call('v66Club',career,listing.sellerId),sellerBalance=seller.balance,buyerBalance=own.balance;
const dayTwoProbe=JSON.parse(JSON.stringify(career));
const dayTwoOffer=call('v72Start',dayTwoProbe,playerId,publicAsk);
assert.strictEqual(dayTwoOffer.stage,'fee-wait');
call('v66NextMarketDay',dayTwoProbe);
assert.strictEqual(dayTwoProbe.world.market.day,2);
assert.notStrictEqual(dayTwoOffer.stage,'fee-wait','ein Angebot von Tag 1 erhält an Tag 2 eine Vereinsantwort');
const bid=call('v72Start',career,playerId,Math.max(10,Math.round(publicAsk*.65/10)*10));
assert.strictEqual(bid.stage,'fee-counter','eine niedrige Ablöse erzeugt sofort eine Gegenforderung');
assert.strictEqual(listing.ask,publicAsk,'die öffentliche Forderung bleibt bei Verhandlungen fest');
call('v72SubmitFee',career,bid.id,bid.counter);
assert.strictEqual(bid.stage,'fee-wait','die Antwort wartet bis zum Tageswechsel');
call('v66NextMarketDay',career);
assert.strictEqual(bid.stage,'contract','nach der Ablöse folgt der Spielervertrag');
assert.throws(()=>call('v72Cancel',career,bid.id),/Ablöseeinigung/,'eine ausgehandelte Ablöse bleibt verbindlich');
assert.strictEqual(listing.ask,publicAsk);
assert(!own.roster.some(player=>player.pid===playerId),'vor dem Vertrag findet kein Wechsel statt');
const minimum=call('v66Consent',career,{...bid,annual:0}).minimum;
 const lowSalary=Math.max(60,minimum-20);
 assert(lowSalary<minimum,'ein Gehaltsgegenangebot ist möglich');
 call('v72SubmitContract',career,bid.id,lowSalary,2,3);
 assert.strictEqual(bid.stage,'contract-wait');
 call('v66NextMarketDay',career);
 assert.strictEqual(bid.stage,'contract-counter','vor dem letzten Tag antwortet der Spieler erst beim Tageswechsel');
 call('v72SubmitContract',career,bid.id,minimum,2,3);
 assert.strictEqual(bid.stage,'contract-wait');
 call('v66NextMarketDay',career);
assert.strictEqual(bid.stage,'completed','der Wechsel wird beim Tageswechsel abgeschlossen');
assert(own.roster.some(player=>player.pid===playerId));
assert.strictEqual(own.balance,buyerBalance-bid.agreedPrice);
assert.strictEqual(seller.balance,sellerBalance+bid.agreedPrice);
assert.strictEqual(listing.ask,publicAsk,'auch nach dem Wechsel wurde die öffentliche Forderung nicht umgeschrieben');
assert.strictEqual(call('v61ValidateCareer',career),true);
const result=market.transferResults.find(item=>item.negotiationId===bid.id&&item.kind==='completed');
assert(result&&result.released&&!result.seen,'das Ergebnis wird beim Tageswechsel freigegeben und bleibt nach Neuladen zur Bestätigung gespeichert');
assert.strictEqual(call('v61ValidateCareer',JSON.parse(JSON.stringify(career))),true);
const deadline=call('v61CreateCareer','GER-2','deadline-list-seed'),deadlineOwn=call('v66Club',deadline,'GER-2');
call('v66ChooseSponsor',deadline,deadlineOwn.id,deadlineOwn.sponsors[0].id);
for(let index=1;index<5;index++)call('v66NextMarketDay',deadline);
assert.strictEqual(deadline.world.market.day,5);
const finalListing=deadline.world.market.saleListings.find(item=>item.status==='active'&&call('v72Willingness',deadline,item.pid,deadlineOwn.id)!=='no'&&item.ask<deadlineOwn.balance&&!deadline.world.market.negotiations.some(entry=>entry.pid===item.pid));
assert(finalListing,'am letzten Tag ist ein offenes Verkaufsangebot vorhanden');
const finalBid=call('v72Start',deadline,finalListing.pid,Math.max(10,Math.round(finalListing.ask*.65/10)*10));
assert.strictEqual(finalBid.stage,'fee-counter');
call('v72SubmitFee',deadline,finalBid.id,finalBid.counter);
call('v66NextMarketDay',deadline);
assert.strictEqual(deadline.world.market.phase,'deadline','begonnene Verhandlungen überdauern den fünften Transfertag');
assert.strictEqual(finalBid.stage,'contract');
const finalMinimum=call('v66Consent',deadline,{...finalBid,annual:0}).minimum;
call('v72SubmitContract',deadline,finalBid.id,Math.max(60,finalMinimum-20),2,3);
assert.strictEqual(finalBid.stage,'contract-counter','am Abschlusstag antwortet der Spieler sofort');
call('v72SubmitContract',deadline,finalBid.id,finalMinimum,2,3);
call('v66NextMarketDay',deadline);
assert.strictEqual(deadline.world.market.phase,'closed');
assert.strictEqual(finalBid.stage,'completed');
assert.strictEqual(call('v61ValidateCareer',deadline),true);
const stalled=call('v61CreateCareer','GER-2','stalled-list-seed'),stalledOwn=call('v66Club',stalled,'GER-2');
call('v66ChooseSponsor',stalled,stalledOwn.id,stalledOwn.sponsors[0].id);
for(let index=1;index<5;index++)call('v66NextMarketDay',stalled);
const stalledListing=stalled.world.market.saleListings.find(item=>item.status==='active'&&call('v72Willingness',stalled,item.pid,stalledOwn.id)!=='no'&&item.ask<stalledOwn.balance&&!stalled.world.market.negotiations.some(entry=>entry.pid===item.pid));
assert(stalledListing);
const stalledBid=call('v72Start',stalled,stalledListing.pid,stalledListing.ask);
call('v66NextMarketDay',stalled);
assert.strictEqual(stalled.world.market.phase,'deadline');
assert.strictEqual(stalledBid.stage,'contract');
call('v66NextMarketDay',stalled);
assert.strictEqual(stalled.world.market.phase,'closed');
assert.strictEqual(stalledBid.stage,'rejected','ohne Spielervertrag scheitert die Einigung erst beim Transferschluss');
const refusal=call('v61CreateCareer','GER-2','refusal-list-seed'),refusalOwn=call('v66Club',refusal,'GER-2');
call('v66ChooseSponsor',refusal,refusalOwn.id,refusalOwn.sponsors[0].id);
refusalOwn.policy.tradition=0;refusalOwn.policy.fans=0;
const unwilling=refusal.world.market.saleListings.find(item=>item.status==='active'&&call('v72Willingness',refusal,item.pid,refusalOwn.id)==='no'&&item.ask<refusalOwn.balance);
assert(unwilling,'eine klare Ablehnung kann geschätzt werden');
const refused=call('v72Start',refusal,unwilling.pid,unwilling.ask);
assert.strictEqual(refused.stage,'refusal-wait','der Versuch führt zu keiner Verhandlung');
assert.strictEqual(call('v66Owner',refusal,unwilling.pid).id,unwilling.sellerId);
call('v66NextMarketDay',refusal);
assert.strictEqual(refused.stage,'rejected','die Absage erscheint erst beim Tageswechsel');
assert.throws(()=>call('v72Start',refusal,unwilling.pid,unwilling.ask),/nächsten Transferfenster/);
assert(refusal.world.market.transferResults.some(item=>item.negotiationId===refused.id&&item.kind==='rejected'&&item.day<refusal.world.market.day));
const competing=call('v61CreateCareer','GER-2','competing-list-seed'),competingOwn=call('v66Club',competing,'GER-2');
call('v66ChooseSponsor',competing,competingOwn.id,competingOwn.sponsors[0].id);
const contested=competing.world.market.saleListings.find(item=>item.status==='active'&&call('v72Willingness',competing,item.pid,competingOwn.id)!=='no'&&item.ask<competingOwn.balance&&!competing.world.market.negotiations.some(entry=>entry.pid===item.pid));
assert(contested);
const human=call('v72Start',competing,contested.pid,contested.ask);
call('v66NextMarketDay',competing);
assert.strictEqual(human.stage,'contract');
const humanSalary=call('v66Consent',competing,{...human,annual:0}).minimum;
const rival=competing.world.clubs.filter(club=>![competingOwn.id,contested.sellerId].includes(club.id)&&club.roster.length<14).sort((a,b)=>b.balance-a.balance).find(club=>call('v66CanAfford',competing,club.id,contested.ask,humanSalary+250));
assert(rival);
const rivalOffer={id:`S${competing.world.season}:test-rival`,pid:contested.pid,buyerId:rival.id,sellerId:contested.sellerId,price:contested.ask,agreedPrice:contested.ask,annual:humanSalary+250,years:3,promise:rival.leagueId?5:0,stage:'ready',createdDay:competing.world.market.day,lastChange:'Vertrag vereinbart.'};
competing.world.market.negotiations.push(rivalOffer);
call('v72SubmitContract',competing,human.id,humanSalary,2,3);
call('v66NextMarketDay',competing);
assert.strictEqual(rivalOffer.stage,'completed','der Spieler wählt das bessere abgeschlossene Vertragsangebot');
assert.strictEqual(human.stage,'rejected','der andere Käufer erhält eine endgültige Ablehnung');
assert(!competingOwn.roster.some(player=>player.pid===contested.pid));
assert(rival.roster.some(player=>player.pid===contested.pid));
assert.strictEqual(rival.ledger.filter(item=>item.id===`${rivalOffer.id}:buy`).length,1);
assert.strictEqual(call('v66Club',competing,contested.sellerId).ledger.filter(item=>item.id===`${rivalOffer.id}:sale`).length,1);
assert.strictEqual(call('v61ValidateCareer',competing),true);
console.log('KI-Verkaufsliste: feste öffentliche Ablöse, Gegenforderung, Vertrag, Tageswechsel, Buchung und Speicherstand geprüft.');
